// Looks up a freely licensed photo for every player via the Wikipedia API
// (pageimages only returns free images) and writes art.js with URL + credit.
import fs from "fs";
const dir = new URL("..", import.meta.url).pathname;
const html = fs.readFileSync(dir + "src/players.js", "utf8");
const DB = eval(html.match(/const DB = (\[[\s\S]*?\n\]);/)[1]);
const titleFor = JSON.parse(fs.readFileSync(dir + "tools/titles.json", "utf8"));
const UA = { "User-Agent": "HoopRoll/1.0 (personal fan game)" };
const sleep = ms => new Promise(r => setTimeout(r, ms));
async function api(q) {
  for (let tries = 0; ; tries++) {
    await sleep(1500);
    const res = await fetch("https://en.wikipedia.org/w/api.php?format=json&formatversion=2&maxlag=5&" + new URLSearchParams(q), { headers: UA });
    const text = await res.text();
    try { return JSON.parse(text); } catch { if (tries > 5) throw new Error(text.slice(0, 100)); await sleep(10000 * (tries + 1)); }
  }
}
const strip = s => (s || "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

const out = {}, missing = [];
const names = DB.map(d => d[0]);
for (let i = 0; i < names.length; i += 20) {
  const batch = names.slice(i, i + 20);
  const titles = batch.map(n => titleFor[n] || n);
  const r = await api({ action: "query", redirects: 1, prop: "pageimages|description", piprop: "thumbnail|name", pithumbsize: 400, pilicense: "free", titles: titles.join("|") });
  const map = {};
  for (const x of [...(r.query.normalized || []), ...(r.query.redirects || [])]) map[x.from] = x.to;
  const pages = Object.fromEntries(r.query.pages.map(p => [p.title, p]));
  for (const n of batch) {
    let t = titleFor[n] || n; while (map[t]) t = map[t];
    const p = pages[t];
    const bball = /basketball/i.test(p?.description || "");
    if (p?.thumbnail && bball) out[n] = { img: p.thumbnail.source, file: p.pageimage, page: t };
    else missing.push(`${n} -> ${t} | ${p?.description || "no page"} | img:${!!p?.thumbnail}`);
  }
}
// credits from Commons metadata
const files = Object.values(out).map(o => o.file);
for (let i = 0; i < files.length; i += 40) {
  const r = await api({ action: "query", prop: "imageinfo", iiprop: "extmetadata", titles: files.slice(i, i + 40).map(f => "File:" + f).join("|") });
  const norm = Object.fromEntries((r.query.normalized || []).map(x => [x.to, x.from]));
  for (const p of r.query.pages) {
    const m = p.imageinfo?.[0]?.extmetadata || {};
    const f = (norm[p.title] || p.title).replace(/^File:/, "");
    for (const o of Object.values(out)) if (o.file === f || o.file.replace(/_/g, " ") === f) {
      o.by = strip(m.Artist?.value).slice(0, 80); o.lic = strip(m.LicenseShortName?.value);
    }
  }
}
fs.writeFileSync(dir + "art.js", "// generated by tools/fetch_art.mjs — photos from Wikimedia Commons\nconst ART=" + JSON.stringify(out) + ";\n");
console.log(Object.keys(out).length + "/" + names.length + " found");
console.log(missing.join("\n"));
